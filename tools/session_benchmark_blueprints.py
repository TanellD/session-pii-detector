MODES = ('partial', 'pair_contact', 'fio', 'yellow', 'document', 'address',
         'split_facts', 'shared', 'unknown_late', 'service', 'repeat', 'person')


def story(split, context, people, mode, document):
    """Границы владельцев задаются автором здесь, значения добавляются позже."""
    style = SPLITS.index(split)
    if people > 1:
        context += [
            ' В кабинете несколько отдельных заявок; уточню имена, чтобы найти нужную запись.',
            ' В списке отображаются разные обращения, поэтому поясню, какие записи там вижу.',
            ' На экране несколько записей. Для поиска нужной перечислю, на кого они оформлены.',
        ][style]
    intro = [
        'Меня зовут [[a:first]].',
        'Отправитель обращения — [[a:first]], это я.',
        'Пишу от себя, я [[a:first]].',
    ][style]
    if mode == 'person':
        intro = ['В анкете моё имя целиком: [[a:person]].',
                 'В моих данных имя в исходной форме: [[a:person]].',
                 'В карточке у меня имя [[a:person]].'][style]
    if not people:
        controls = [
            ['Личных данных в форме ещё нет, нужен только порядок заполнения.'],
            [['Телефон самого сервиса [[s:phone]], звонок обрывается.',
              'Контакт приёмной для справок: [[s:phone]], ответа пока нет.',
              'По номеру службы поддержки [[s:phone]] идёт автоответчик.'][style]],
            [['В поле осталась строка [[u:bad_phone]], форма её не принимает.',
              'Набор [[u:bad_phone]] случайно попал в поле номера.',
              'Вместо номера вижу [[u:bad_phone]], как очистить поле?'][style]],
            [['На старой бумажке контакт [[u:email]], подписи нет.',
              'Нашёл адрес почты [[u:email]], но неизвестно, кому он принадлежит.',
              'В черновике сохранилось [[u:email]], владельца не знаю.'][style]],
            [['Номер в документе скрыт: [[u:masked_card]], доступны только последние цифры.',
              'В выписке карта показана как [[u:masked_card]], целиком номера нет.',
              'Карта в квитанции замаскирована: [[u:masked_card]].'][style]],
        ]
        return [context, *controls[mode]]
    lines = [context, intro]
    for owner in 'bc'[:people-1]:
        lines.append([
            f'Есть ещё отдельная заявка, имя в ней: [[{owner}:first]].',
            f'Параллельно обращается [[{owner}:first]], заявка отдельная.',
            f'Другая запись есть у человека по имени [[{owner}:first]].',
        ][style])
    if people == 3:
        lines[-1] = [f'Третья запись оформлена на имя [[c:first]].',
                     f'И ещё одна отдельная анкета: [[c:first]].',
                     f'Кроме этих двух записей есть заявка: [[c:first]].'][style]
    last = ['Моя фамилия [[a:last]].', 'Фамилия в моей анкете — [[a:last]].',
            'Для поиска записи уточню свою фамилию: [[a:last]].'][style]
    phone = ['Мой телефон [[a:phone]].', 'Связаться со мной можно по личному номеру [[a:phone]].',
             'На звонки отвечаю по своему номеру [[a:phone]].'][style]
    email = ['Моя почта [[a:email]].', 'Для ответа мне используйте личную почту [[a:email]].',
             'Письмо мне можно отправить на [[a:email]].'][style]
    if mode == 'partial':
        lines += [['Мне сейчас [[a:age]], возможно, возраст не сохранился.',
                   'В моей анкете возраст указан как [[a:age]].',
                   'Мой возраст в карточке — [[a:age]].'][style], phone]
    elif mode == 'pair_contact':
        lines += [last, phone if document in ('inn', 'card') else email]
    elif mode == 'fio':
        lines += [last, ['Моё отчество [[a:patronymic]].', 'У меня отчество [[a:patronymic]].',
                         'Отчество в моей записи: [[a:patronymic]].'][style]]
    elif mode == 'yellow':
        lines += [
            ['Похоже, в комментарий к моей заявке попал кусок моей рабочей анкеты. Хочу убрать лишнее; вот что там сохранилось.',
             'Нужно удалить из обращения вставленный текст моего профиля. Переписываю поля, которые там вижу.',
             'В заявку случайно прикрепилась часть моей анкеты о работе. Уточняю её содержимое, чтобы это можно было удалить.'][style],
            ['Моя профессия — [[a:occupation]], работодатель [[a:organization]].',
             'Работаю по профессии [[a:occupation]] в [[a:organization]].',
             'Для моей анкеты: профессия [[a:occupation]], место работы [[a:organization]].'][style],
            ['Мой город [[a:geography]], пол в анкете [[a:sex]].',
             'У меня в профиле город [[a:geography]] и пол [[a:sex]].',
             'В своей записи указываю город [[a:geography]], пол — [[a:sex]].'][style]]
    elif mode == 'document':
        label = dict(inn='ИНН', snils='СНИЛС', card='номер карты', passport='паспорт')[document]
        lines += [[f'В старом комментарии остались мои реквизиты, хочу их убрать. Там мой {label}: [[a:{document}]].',
                   f'В обращение попал лишний фрагмент моих документов: {label} [[a:{document}]]. Можно удалить этот фрагмент?',
                   f'Нужно очистить текст, случайно вставленный мной в заявку. В нём мой {label} [[a:{document}]].'][style]]
    elif mode == 'address':
        lines += [last, ['Мой адрес проживания [[a:address]].',
                         'Живу по адресу [[a:address]], это квартира.',
                         'Я проживаю здесь: [[a:address]].'][style]]
    elif mode == 'split_facts':
        lines += [last]
        if people > 1:
            lines += [['Личный контакт для другой записи: [[b:first]], телефон [[b:phone]].',
                       'Контакт для отдельной заявки: [[b:first]], телефон [[b:phone]].',
                       '[[b:first]] просит звонить на свой номер [[b:phone]].'][style]]
        else:
            lines += [['Телефон приёмной [[s:phone]], моего номера в форме нет.',
                       'Для справок дали номер учреждения [[s:phone]].',
                       'В памятке напечатан служебный телефон [[s:phone]].'][style]]
    elif mode == 'shared':
        if people > 1:
            lines += [last, ['Я и [[b:first]] пользуемся общим личным телефоном [[ab:phone]].',
                            'У нас двоих, я и [[b:first]], один личный номер [[ab:phone]].',
                            'Общим личным телефоном пользуемся я и [[b:first]]: [[ab:phone]].'][style]]
        else:
            lines += [phone, ['Повторю мой номер: [[a:phone]].', 'Мой контакт тот же [[a:phone]].',
                              'Ещё раз для связи со мной: [[a:phone]].'][style]]
    elif mode == 'unknown_late':
        lines += [['Без подписи в заметке записан телефон [[u:phone]].',
                   'На полях есть номер [[u:phone]], чей он — не указано.',
                   'Сохранился неподписанный контакт [[u:phone]].'][style], last]
        if people > 1:
            lines += [['Пришло уточнение: [[b:first]], личный номер [[b:phone]].',
                       'Вот уточнение: [[b:first]], личный телефон [[b:phone]].',
                       'Новый контакт для другой заявки: [[b:first]], личный телефон [[b:phone]].'][style]]
        lines += [email]
    elif mode == 'service':
        lines += [last, ['В поддержке почта [[s:email]], мне пока не ответили.',
                         'Общая почта организации [[s:email]], ответа нет.',
                         'Для справок опубликована почта сервиса [[s:email]].'][style]]
    elif mode == 'repeat':
        lines += [phone, ['Мой телефон всё тот же [[a:phone]].',
                         'Дублирую контакт для моей записи [[a:phone]].',
                         'Тот же личный номер повторю: [[a:phone]].'][style]]
    elif mode == 'person':
        lines += [email]
    return lines
